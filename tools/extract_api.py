#!/usr/bin/env python3
"""Turns the APIDump lines from Lua.log and the game's own Lua sources into docs/api/*.md.

Usage: tools/extract_api.py [--log PATH] [--reference DIR] [--out DIR]
"""
import argparse
import os
import re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_LOG = os.path.expanduser(
    "~/Library/Application Support/Sid Meier's Civilization VI/"
    "Firaxis Games/Sid Meier's Civilization VI/Logs/Lua.log")
DEFAULT_REFERENCE = os.path.join(ROOT, "reference", "GameAssets")
DEFAULT_OUT = os.path.join(ROOT, "docs", "api")

EVENT_RE = re.compile(r"\b(Events|LuaEvents|GameEvents)\.(\w+)\s*(\.\s*(Add|Remove)\s*\(|\()")
FILES_PER_EVENT = 6


class Dump:
    def __init__(self):
        self.globals = {}
        self.members = defaultdict(dict)
        self.fired = defaultdict(list)
        self.notes = []


def read_dump(log_path):
    dumps = defaultdict(Dump)
    with open(log_path, encoding="utf-8", errors="replace") as log:
        for line in log:
            start = line.find("APIDUMP\t")
            if start < 0:
                continue
            fields = line[start:].rstrip("\r\n").split("\t", 4)
            if len(fields) < 4:
                continue
            _, context, kind, path = fields[:4]
            detail = fields[4] if len(fields) > 4 else ""
            dump = dumps[context]
            if kind == "GLOBAL":
                dump.globals[path] = detail
            elif kind == "MEMBER":
                parent, _, name = path.rpartition(".")
                dump.members[parent][name] = detail
            elif kind == "FIRED":
                dump.fired[path].append(detail)
            elif kind in ("ERROR", "SPY", "SEE"):
                dump.notes.append(f"{kind} `{path}` {detail}")
    return dumps


def scan_usage(reference):
    subscribers = defaultdict(set)
    callers = defaultdict(set)
    if not os.path.isdir(reference):
        return subscribers, callers
    for folder, _, files in os.walk(reference, followlinks=True):
        for name in files:
            if not name.endswith(".lua"):
                continue
            path = os.path.join(folder, name)
            rel = os.path.relpath(path, reference)
            with open(path, encoding="utf-8", errors="replace") as source:
                text = source.read()
            for match in EVENT_RE.finditer(text):
                event = f"{match.group(1)}.{match.group(2)}"
                if match.group(4) == "Add":
                    subscribers[event].add(rel)
                elif match.group(4) is None:
                    callers[event].add(rel)
    return subscribers, callers


def file_list(files):
    ordered = sorted(files)
    shown = ", ".join(f"`{f}`" for f in ordered[:FILES_PER_EVENT])
    if len(ordered) > FILES_PER_EVENT:
        shown += f" and {len(ordered) - FILES_PER_EVENT} more"
    return shown


def write_context(out_dir, context, dump):
    lines = [f"# {context} context", "",
             "Generated by tools/extract_api.py from the APIDump mod output. Do not edit.", ""]
    lines += ["## Globals", ""]
    for name in sorted(dump.globals):
        lines.append(f"- `{name}` — {dump.globals[name]}")
    lines.append("")
    for parent in sorted(dump.members):
        lines += [f"## {parent}", ""]
        for name, detail in sorted(dump.members[parent].items()):
            lines.append(f"- `{name}` — {detail}")
        lines.append("")
    if dump.notes:
        lines += ["## Dump notes", ""] + [f"- {note}" for note in dump.notes] + [""]
    with open(os.path.join(out_dir, f"{context}.md"), "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def write_events(out_dir, dumps, subscribers, callers):
    known = defaultdict(set)
    fired = {}
    for context, dump in dumps.items():
        for parent, members in dump.members.items():
            if parent in ("Events", "LuaEvents", "GameEvents"):
                for name in members:
                    known[f"{parent}.{name}"].add(context)
        for event, calls in dump.fired.items():
            fired[event] = calls
    names = set(known) | set(subscribers) | set(callers) | set(fired)

    lines = ["# Events", "",
             "Generated by tools/extract_api.py. Arguments are the first firings seen by the",
             "APIDump mod; files are where the game's own Lua subscribes to or fires the event.", ""]
    for table in ("Events", "LuaEvents", "GameEvents"):
        group = sorted(n for n in names if n.startswith(table + "."))
        if not group:
            continue
        lines += [f"## {table}", ""]
        for event in group:
            lines.append(f"### `{event}`")
            lines.append("")
            if known.get(event):
                lines.append(f"- Exposed in: {', '.join(sorted(known[event]))}")
            for call in fired.get(event, []):
                lines.append(f"- Fired with: {call or '(no arguments)'}")
            if subscribers.get(event):
                lines.append(f"- Subscribed in: {file_list(subscribers[event])}")
            if callers.get(event):
                lines.append(f"- Fired from: {file_list(callers[event])}")
            lines.append("")
    with open(os.path.join(out_dir, "Events.md"), "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--log", default=DEFAULT_LOG)
    parser.add_argument("--reference", default=DEFAULT_REFERENCE)
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args()

    dumps = read_dump(args.log) if os.path.exists(args.log) else {}
    if not dumps:
        print(f"No APIDUMP lines in {args.log}; only the source scan will be written.")
    subscribers, callers = scan_usage(args.reference)

    os.makedirs(args.out, exist_ok=True)
    for context, dump in dumps.items():
        write_context(args.out, context, dump)
    write_events(args.out, dumps, subscribers, callers)
    print(f"Contexts: {', '.join(sorted(dumps)) or 'none'}; "
          f"events from sources: {len(set(subscribers) | set(callers))}; written to {args.out}")


if __name__ == "__main__":
    main()
